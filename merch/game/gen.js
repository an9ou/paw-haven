// Merch part 8b: writes merch/game/61_merch_enc.js, the small encoder the game copies to game/src/61_merch_enc.js (docs/design/merch/PART8.md).
//   node merch/game/gen.js           write the file
//   node merch/game/gen.js --check   fail (exit 1) when the committed file is not what this script would write now
// One source of truth: the WEAR table, the recipe, the name rules and the wire format are copied word for word from merch/pawprint_core.js
// (the declarations listed in TAKE) and merch/names.js, so the game's link is PawPrint's own merchEncode. This script is not one of the files
// that feed PawPrint.ART_VER (tools/merch_build.js HASHED), and it only reads them.
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..', '..'), OUT = path.join(__dirname, '61_merch_enc.js');
const rd = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');

// the declarations of PawPrintMake that the recipe and the encoder need, in their order in the core (2-space indented, one statement each)
const TAKE = ['VERSION', 'BREEDS', 'EYES', 'AGES', 'LOCI', 'XLOCI', 'hashId', 'fnv16', 'isInt', 'artKnows', 'cleanName', 'cnt', 'okPair', 'geneCode', 'genesFrom',
  'ageStage', 'merchRecipe', 'check', 'B64', 'b64', 'utf8', 'genes16', 'merchEncode'];

// one top-level statement of the core, from "  const NAME" / "  function NAME" to its end (brackets balanced, strings and regexes skipped)
function grab(src, name) {
  const m = new RegExp('^  (?:const|function) ' + name + '\\b', 'm').exec(src);
  if (!m) throw new Error('merch/pawprint_core.js: no top-level ' + name);
  const fn = src.startsWith('  function', m.index);
  let i = m.index, depth = 0, prev = '';
  for (; i < src.length; i++) {
    const c = src[i];
    if (c === "'" || c === '"' || c === '`') { const q = c; i++; while (i < src.length && src[i] !== q) { if (src[i] === '\\') i++; i++; } prev = q; continue; }
    if (c === '/' && src[i + 1] === '/') { while (i < src.length && src[i] !== '\n') i++; continue; }
    if (c === '/' && /[(,=:[!&|?{};]/.test(prev)) { i++; let cls = false; while (i < src.length && (src[i] !== '/' || cls)) { if (src[i] === '\\') i++; else if (src[i] === '[') cls = true; else if (src[i] === ']') cls = false; i++; } prev = '/'; continue; }
    if ('([{'.includes(c)) depth++;
    else if (')]}'.includes(c)) { depth--; if (fn && depth === 0 && c === '}') { i++; break; } }
    else if (c === ';' && depth === 0 && !fn) { i++; break; }
    if (!/\s/.test(c)) prev = c;
  }
  let out = src.slice(m.index, i);
  const tail = /^[^\n]*/.exec(src.slice(i))[0]; if (/^\s*\/\/.*$/.test(tail)) out += tail; // its own line comment
  return out;
}

function make() {
  const core = rd('merch/pawprint_core.js'), names = rd('merch/names.js');
  const font = require(path.join(ROOT, 'merch', 'pawprint_font.js')), NAMES = require(path.join(ROOT, 'merch', 'names.js'));
  const chars = Array.from(NAMES.CHARS).filter((c) => font.g[c]).join(''); // what cleanName needs of the font: which allowed letters it draws
  const slots = grab(core, 'SLOTS'), wear = grab(core, 'WEAR');
  const take = TAKE.map((n) => grab(core, n));
  return `/* Doodle Doggo: the merch link's encoder, for the game (game/src/61_merch_enc.js, one shared scope: plain declarations, no module, no globals).
   GENERATED by merch/game/gen.js from merch/pawprint_core.js and merch/names.js: do not edit here; change the core, then run
   node merch/game/gen.js (node merch/game/gen.js --check says whether this copy is current). docs/design/merch/PART8.md.
   Declares MERCH_WEAR, merchRecipe(dog), merchEncode(recipes), merchLink(dogs, opts) and private merch* helpers. Reads only window.PawGenes
   (BREEDS, phenotype, STARTER_GENES) and window.PawArt (DOGS), lazily. No art, no decode, no network, no storage, no DOM.
     merchRecipe(dog)        a dog of S.dogs -> its looks only (breed, genes as counts, eyes, art seed, age stage, sex, sparkle, mix head, worn
                             items, the name if the print can draw it), exactly PawPrint.merchRecipe; null when it cannot be encoded
     merchEncode(recipes)    one recipe or 1-8 -> the base64url text after #p= (PawPrint.merchEncode); throws on a bad recipe
     merchLink(dogs, opts)   -> 'https://doodledoggo.app/merch/#p=...' or null when no dog can go. opts: active (a dog id, sent first),
                             base (another page address, e.g. the test copy), share ({ prod: 'mug', pose: 'happy' }: that one dog, and
                             &prod=mug&pose=happy&from=share), max (the longest text after #, 1024 at most; for tests). 8 dogs at most;
                             a dog that cannot be encoded is left out; dogs are dropped from the end until the text after # fits. */
const MERCH_WEAR = (function () {
  'use strict';
${slots}
${wear}
  return Object.freeze(WEAR.map((w) => Object.freeze(w)));
})();
const MERCH_SHARE = { prod: ['mug', 'tee'], pose: ['stand', 'sit', 'happy'] }; // what the merch page can open with (its launch products and their poses)
let merchKitC = null;
function merchKit() {
  if (merchKitC) return merchKitC;
  const PA = window.PawArt, PG = window.PawGenes;
  if (!PA || !Array.isArray(PA.DOGS) || !PG || !Array.isArray(PG.BREEDS) || typeof PG.phenotype !== 'function') return null;
  return (merchKitC = merchMake(PA, PG));
}
// the core's own code, inside its own scope (so none of its names meets the game's)
function merchMake(PA, PG) {
  'use strict';
  const WEAR = MERCH_WEAR;
  const NAMES = (function (module, self) {
${names}
  return self.PawNames; })(undefined, {});
  const FONT = { g: {} }; Array.from(${JSON.stringify(chars)}).forEach((c) => { FONT.g[c] = 1; }); // the letters merch/pawprint_font.js draws
${take.join('\n')}
  return { MAX_DOGS, HASH_MAX, merchRecipe, merchEncode, check };
}
function merchRecipe(dog) {
  const k = merchKit(); if (!k) return null;
  try { const r = k.merchRecipe(dog); return r && k.check(r).ok ? r : null; } catch (e) { return null; }
}
function merchEncode(recipes) {
  const k = merchKit(); if (!k) throw new Error('merch: no PawGenes or PawArt');
  return k.merchEncode(recipes);
}
function merchLink(dogs, opts) {
  opts = opts || {}; const k = merchKit(); if (!k) return null;
  const list = Array.isArray(dogs) ? dogs.slice() : dogs ? [dogs] : [];
  if (opts.active != null) { const i = list.findIndex((d) => d && d.id === opts.active); if (i > 0) list.unshift(list.splice(i, 1)[0]); }
  const sh = opts.share, share = !!sh;
  const tail = sh && MERCH_SHARE.prod.includes(sh.prod) && MERCH_SHARE.pose.includes(sh.pose) ? '&prod=' + sh.prod + '&pose=' + sh.pose + '&from=share' : '';
  const most = share ? 1 : k.MAX_DOGS, max = opts.max > 0 ? Math.min(opts.max, k.HASH_MAX) : k.HASH_MAX, rs = [];
  for (const d of list) {
    if (rs.length >= most) break;
    const r = merchRecipe(d); if (!r) continue;
    try { k.merchEncode([r]); } catch (e) { continue; }
    rs.push(r);
  }
  const base = String(opts.base || 'https://doodledoggo.app/merch/').split('#')[0];
  for (; rs.length; rs.pop()) { const h = 'p=' + k.merchEncode(rs) + tail; if (h.length <= max) return base + '#' + h; }
  return null;
}
`;
}

if (require.main === module) {
  const want = make();
  if (process.argv.includes('--check')) {
    const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (have !== want) { console.error('merch/game/61_merch_enc.js is stale: run node merch/game/gen.js'); process.exit(1); }
    console.log('merch/game/61_merch_enc.js is current (' + (Buffer.byteLength(want) / 1024).toFixed(1) + ' KB)');
  } else { fs.writeFileSync(OUT, want); console.log('wrote merch/game/61_merch_enc.js (' + (Buffer.byteLength(want) / 1024).toFixed(1) + ' KB)'); }
} else module.exports = { make, grab, TAKE, OUT };
