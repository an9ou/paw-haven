// Turns _site/ (from tools/pages.js) into a small Cloudflare Worker that serves doodledoggo.app.
//   node tools/cf_site.js            -> _cfsite/worker.js + _cfsite/parts.txt (one "name type" line per upload part)
// Why a Worker and not Pages: Pages and Workers-assets uploads authenticate with a short-lived upload JWT, which the cloud
// session's proxy replaces with the account API token, so those uploads fail there. A Worker script upload needs only the
// API token. The whole site (about 1.2 MB gzipped) fits in one Worker: index.html as a text module, the brand kit as data modules.
// www.doodledoggo.app answers with a 301 to the apex, keeping the path.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), site = path.join(root, '_site'), out = path.join(root, '_cfsite');
if (!fs.existsSync(path.join(site, 'index.html'))) { console.error('no _site/index.html: run node game/build.js publish && node tools/pages.js'); process.exit(1); }
fs.rmSync(out, { recursive: true, force: true }); fs.mkdirSync(out, { recursive: true });
const TYPES = { html: 'text/html; charset=utf-8', svg: 'image/svg+xml', png: 'image/png', webmanifest: 'application/manifest+json' };
const files = fs.readdirSync(site).filter((f) => !f.startsWith('.') && TYPES[f.split('.').pop()]).sort();
const parts = [], imports = [], table = [];
files.forEach((f, i) => {
  const ext = f.split('.').pop(), text = ext !== 'png';
  fs.copyFileSync(path.join(site, f), path.join(out, f));
  parts.push(`${f} ${text ? 'text/plain' : 'application/octet-stream'}`); // text/plain = Text module, octet-stream = Data module
  imports.push(`import f${i} from './${f}';`);
  table.push(`  '/${f}': [f${i}, '${TYPES[ext]}'],`);
});
const worker = `// Generated by tools/cf_site.js from _site/. Do not edit: run bash tools/cf_pages_deploy.sh.
${imports.join('\n')}
const FILES = {
${table.join('\n')}
};
const APEX = 'doodledoggo.app';
export default {
  async fetch(req) {
    const url = new URL(req.url);
    if (url.hostname === 'www.' + APEX) return Response.redirect('https://' + APEX + url.pathname + url.search, 301);
    if (req.method !== 'GET' && req.method !== 'HEAD') return new Response('Method not allowed', { status: 405, headers: { allow: 'GET, HEAD' } });
    const hit = FILES[url.pathname === '/' ? '/index.html' : url.pathname];
    if (!hit) return new Response('Not found', { status: 404, headers: { 'content-type': 'text/plain; charset=utf-8' } });
    const html = hit[1].startsWith('text/html');
    const headers = { 'content-type': hit[1], 'cache-control': html ? 'public, max-age=300' : 'public, max-age=86400', 'x-content-type-options': 'nosniff' };
    return new Response(req.method === 'HEAD' ? null : hit[0], { headers });
  }
};
`;
fs.writeFileSync(path.join(out, 'worker.js'), worker);
fs.writeFileSync(path.join(out, 'parts.txt'), parts.join('\n') + '\n');
console.log('wrote _cfsite/worker.js +', files.length, 'files');
