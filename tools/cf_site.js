// Turns site/ (the doodledoggo.app introduction site, v2.8.2) plus the brand kit into a small Cloudflare Worker.
//   node tools/cf_site.js            -> _cfsite/worker.js + its modules + _cfsite/parts.txt (one "name type" line per upload part)
//   bash tools/cf_pages_deploy.sh    builds this and deploys it to doodledoggo.app (needs the owner's go-ahead)
// Pages: / (index.html), /privacy, /reset (the Forgot password link: sets the new password through the Worker pawhaven-api).
// The game itself is played on itch.io (https://an9ou.itch.io/doodle-doggo); this site only introduces it.
// Why a Worker and not Pages: Pages and Workers-assets uploads authenticate with a short-lived upload JWT, which the cloud
// session's proxy replaces with the account API token, so those uploads fail there. A Worker script upload needs only the
// API token. www.doodledoggo.app answers with a 301 to the apex, keeping the path.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), site = path.join(root, 'site'), brand = path.join(root, 'brand'), out = path.join(root, '_cfsite');
const TYPES = { html: 'text/html; charset=utf-8', css: 'text/css; charset=utf-8', svg: 'image/svg+xml', png: 'image/png', webp: 'image/webp', woff2: 'font/woff2', webmanifest: 'application/manifest+json', txt: 'text/plain; charset=utf-8' };
const TEXT = new Set(['html', 'css', 'svg', 'webmanifest', 'txt']);
// url path -> source file
const files = {};
const walk = (dir, base) => fs.readdirSync(dir).forEach((f) => {
  const p = path.join(dir, f);
  if (fs.statSync(p).isDirectory()) return walk(p, base + f + '/');
  if (TYPES[f.split('.').pop()]) files['/' + base + f] = p;
});
walk(site, '');
['favicon.svg', 'icon-32.png', 'icon-180.png', 'icon-192.png', 'icon-512.png', 'icon-512-maskable.png', 'site.webmanifest', 'logo-1200x630.png', 'doodle-doggo-logo.svg', 'doodle-doggo-icon.svg']
  .forEach((f) => { files['/' + f] = path.join(brand, f); });
const PRETTY = { '/': '/index.html', '/privacy': '/privacy.html', '/reset': '/reset.html' };

fs.rmSync(out, { recursive: true, force: true }); fs.mkdirSync(out, { recursive: true });
const parts = [], imports = [], table = [];
Object.keys(files).sort().forEach((u, i) => {
  const ext = u.split('.').pop(), mod = u.slice(1).replace(/\//g, '__'); // flat module names
  fs.copyFileSync(files[u], path.join(out, mod));
  parts.push(`${mod} ${TEXT.has(ext) ? 'text/plain' : 'application/octet-stream'}`); // text/plain = Text module, octet-stream = Data module
  imports.push(`import f${i} from './${mod}';`);
  table.push(`  '${u}': [f${i}, '${TYPES[ext]}'],`);
});
const CSP = "default-src 'self'; script-src 'self' 'unsafe-inline'; style-src 'self' 'unsafe-inline'; img-src 'self'; font-src 'self'; connect-src https://pawhaven-api.ansonyuen0108.workers.dev; frame-ancestors 'none'; base-uri 'none'; form-action 'self'";
const worker = `// Generated by tools/cf_site.js from site/ and brand/. Do not edit: run node tools/cf_site.js (or bash tools/cf_pages_deploy.sh).
${imports.join('\n')}
const FILES = {
${table.join('\n')}
};
const PRETTY = ${JSON.stringify(PRETTY)};
const APEX = 'doodledoggo.app';
const CSP = ${JSON.stringify(CSP)};
export default {
  async fetch(req) {
    const url = new URL(req.url);
    if (url.hostname === 'www.' + APEX) return Response.redirect('https://' + APEX + url.pathname + url.search, 301);
    if (req.method !== 'GET' && req.method !== 'HEAD') return new Response('Method not allowed', { status: 405, headers: { allow: 'GET, HEAD' } });
    let p = url.pathname.length > 1 ? url.pathname.replace(/\\/+$/, '') : '/';
    if (p.endsWith('.html') && FILES[p]) return Response.redirect('https://' + url.host + (p === '/index.html' ? '/' : p.slice(0, -5)) + url.search, 301);
    const hit = FILES[PRETTY[p] || p];
    const headers = { 'x-content-type-options': 'nosniff', 'referrer-policy': 'strict-origin-when-cross-origin', 'content-security-policy': CSP };
    if (!hit) return new Response(FILES['/index.html'] ? '<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><link rel="stylesheet" href="/style.css"><main class="page"><div class="sheet center"><h1>Woof? Nothing here.</h1><p><a class="play" href="/">Doodle Doggo home</a></p></div></main>' : 'Not found',
      { status: 404, headers: Object.assign(headers, { 'content-type': 'text/html; charset=utf-8' }) });
    const html = hit[1].startsWith('text/html');
    Object.assign(headers, { 'content-type': hit[1], 'cache-control': html ? 'public, max-age=300' : 'public, max-age=86400' });
    if (p === '/reset') headers['referrer-policy'] = 'no-referrer';
    return new Response(req.method === 'HEAD' ? null : hit[0], { headers });
  }
};
`;
fs.writeFileSync(path.join(out, 'worker.js'), worker);
fs.writeFileSync(path.join(out, 'parts.txt'), parts.join('\n') + '\n');
const size = Object.values(files).reduce((n, f) => n + fs.statSync(f).size, 0);
console.log('wrote _cfsite/worker.js +', Object.keys(files).length, 'files,', (size / 1e6).toFixed(2), 'MB');
