#!/usr/bin/env node
// v2.9 PHOTO lane: writes game/src/35b_photo_fonts.js from the two OFL fonts in site/fonts/ (Caveat, Patrick Hand; latin subsets, woff2).
// The saved photo is an SVG drawn to a canvas, and an SVG used as an image cannot load page fonts or files, so the fonts travel inside it as
// @font-face data URIs. Run `node tools/photo_fonts.js` after changing the fonts. The output is about 133 KB (V29.md 5.4: under about 140 KB).
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const b64 = (f) => fs.readFileSync(path.join(root, 'site', 'fonts', f)).toString('base64');
const css = [
  ["'Caveat'", '500 700', 'caveat.woff2'],
  ["'Patrick Hand'", '400', 'patrick-hand.woff2']
].map(([fam, wt, f]) => `@font-face{font-family:${fam};font-weight:${wt};src:url(data:font/woff2;base64,${b64(f)}) format('woff2')}`).join('');
const out = `/* GENERATED by tools/photo_fonts.js from site/fonts/ (Caveat and Patrick Hand, SIL Open Font License 1.1). Do not edit by hand.
   v2.9 PHOTO lane: embedded into the saved postcard (35_photo.js), because an SVG drawn to a canvas cannot load page fonts. */
const PH_FONT_CSS = ${JSON.stringify(css)};
`;
fs.writeFileSync(path.join(root, 'game', 'src', '35b_photo_fonts.js'), out);
console.log('game/src/35b_photo_fonts.js', Math.round(out.length / 1024) + ' KB');
