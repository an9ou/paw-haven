#!/usr/bin/env node
// Doodle Doggo v2.14 (V214.md 4.4): pack the string tables into game/i18n/packed.js, the one file the builds put into the pawi18n slot.
//   node tools/i18n_pack.js           write game/i18n/packed.js
//   node tools/i18n_pack.js --check   only compare (exit 1 when packed.js is out of date with en.json, the tables, the glossaries or the fonts)
// Output (generated, committed, never edited by hand, like 35b_photo_fonts.js):
//   window.PAW_I18N = { v: 1, keys: [every game/i18n/en.json key, sorted], ja: [text or null per key], ... (CODES order, no en),
//                       fonts: { ja: [{ f: 'DD Local', u: 'ja.woff2?v=<sha8>', r: 'U+3001-3002,...' }], ... } };
// The English stays in the code (tt() falls back to it per key), so en has no array. A language array is cut after its last text.
// Each language's `data.breed_names.<key>` comes from game/i18n/<lang>.json, else from the glossary `breeds` (game/i18n/glossary/<lang>.json).
// Keys of a table that are not in en.json are dropped with a warning (a renamed key: the translation is kept in <lang>.json for the record).
// fonts: the @font-face blocks of game/fonts/i18n/<lang>.css (written by `node tools/i18n_fonts.js <lang> --for game`), so 00b_i18n.js loads
// only the current language's face from fonts/i18n/ next to the page (docs/i18n/FONTS.md section 5).
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..'), I = path.join(ROOT, 'game/i18n'), FONTS = path.join(ROOT, 'game/fonts/i18n');
const M = require(path.join(I, 'msg.js'));
const CHECK = process.argv.includes('--check'), QUIET = process.argv.includes('--quiet');
const die = (m) => { console.error('i18n_pack: ' + m); process.exit(1); };
const readJson = (f) => { try { return JSON.parse(fs.readFileSync(f, 'utf8')); } catch (e) { die(path.relative(ROOT, f) + ': ' + e.message); } return null; };

if (!fs.existsSync(path.join(I, 'en.json'))) die('game/i18n/en.json is missing: run node tools/i18n_extract.js --en first');
const en = readJson(path.join(I, 'en.json'));
const keys = Object.keys(en).sort(), at = new Map(keys.map((k, i) => [k, i]));
const out = { v: 1, keys };
const report = [];
for (const lang of M.CODES.filter((c) => c !== 'en')) {
  const f = path.join(I, lang + '.json'), g = path.join(I, 'glossary', lang + '.json');
  const tab = fs.existsSync(f) ? readJson(f) : {}, gl = fs.existsSync(g) ? readJson(g) : {};
  const arr = new Array(keys.length).fill(null); let n = 0, drop = 0;
  for (const [k, v] of Object.entries(tab)) {
    if (typeof v !== 'string' || v === '') continue;
    if (!at.has(k)) { drop++; continue; }
    arr[at.get(k)] = v; n++;
  }
  for (const [b, v] of Object.entries(gl.breeds || {})) { const k = 'data.breed_names.' + b; if (at.has(k) && arr[at.get(k)] == null && typeof v === 'string' && v) { arr[at.get(k)] = v; n++; } }
  let last = arr.length; while (last > 0 && arr[last - 1] == null) last--;
  out[lang] = arr.slice(0, last);
  report.push(`${lang} ${n}/${keys.length}${drop ? ` (${drop} keys not in en.json, dropped)` : ''}`);
}
// fonts
const fonts = {};
if (fs.existsSync(FONTS)) for (const lang of M.CODES.filter((c) => c !== 'en')) {
  const css = path.join(FONTS, lang + '.css'); if (!fs.existsSync(css)) continue;
  const list = [];
  for (const m of fs.readFileSync(css, 'utf8').matchAll(/@font-face\s*\{([^}]*)\}/g)) {
    const b = m[1], fam = /font-family:\s*'([^']+)'/.exec(b), src = /url\(([^)]+)\)/.exec(b), rng = /unicode-range:\s*([^;}]+)/.exec(b);
    if (!fam || !src) continue;
    const u = src[1].replace(/^["']|["']$/g, '').split('/').pop(), file = u.split('?')[0];
    if (!fs.existsSync(path.join(FONTS, file))) die(`game/fonts/i18n/${lang}.css names ${file}, which is missing`);
    list.push({ f: fam[1], u, r: rng ? rng[1].trim() : '' });
  }
  if (list.length) fonts[lang] = list;
}
out.fonts = fonts;
// one language per line: small diffs when a table changes. `</` is written as `<\/` so the text can sit inside a <script>.
const js = (v) => JSON.stringify(v).replace(/<\//g, '<\\/');
const lines = ['v: 1', 'keys: ' + js(keys)].concat(M.CODES.filter((c) => c !== 'en').map((c) => `${js(c)}: ${js(out[c])}`), ['fonts: ' + js(fonts)]);
const text = '/* GENERATED by tools/i18n_pack.js from game/i18n/en.json, game/i18n/<lang>.json, the glossaries and game/fonts/i18n. Do not edit: rerun the tool. */\n'
  + 'window.PAW_I18N = {\n' + lines.join(',\n') + '\n};\n';
const OUT = path.join(I, 'packed.js');
if (CHECK) {
  const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (old !== text) die('game/i18n/packed.js is out of date: run node tools/i18n_pack.js');
  console.log(`game/i18n/packed.js is up to date (${keys.length} keys)`); process.exit(0);
}
fs.writeFileSync(OUT, text);
console.log(`wrote game/i18n/packed.js: ${keys.length} keys, ${(Buffer.byteLength(text) / 1e3).toFixed(0)} KB, fonts for ${Object.keys(fonts).join(' ') || 'none'}`);
if (!QUIET) console.log('  ' + report.join(' · '));
