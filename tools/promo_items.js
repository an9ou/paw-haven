// Gift codes (v2.25.5, PROMO.md): writes tools/promo_items.json, the names tools/promo.sh accepts in a reward, read from the game's own tables
// (window.__paw.pr.catalog() in game/src/55_promo.js): every `promo: true` item (code-only), what the shops sell (never the Kind shop's paid
// looks or earned rewards such as the Golden Collar), and the dog-safe treats (FOOD without Fresh Water).
//   NODE_PATH=$(npm root -g) PAW_ARGS=--ignore-certificate-errors node tools/promo_items.js [--check]
// Run it after any item table change (the promo suite fails while the file is stale). --check exits 1 when the file is stale.
const fs = require('fs'), path = require('path');
const L = require('./paw_sim_lib');
const OUT = path.join(__dirname, 'promo_items.json');
(async () => {
  L.ensureHarness(false);
  const b = await L.launch();
  let cat;
  try {
    const p = await L.newPage(b); await p.goto('file://' + L.HARNESS);
    if (!(await L.until(p, () => !!(window.__paw && window.__paw.pr), null, 60000))) throw new Error('the game did not load');
    cat = await p.evaluate(() => window.__paw.pr.catalog());
  } finally { await b.close(); }
  const out = '{\n "note": "Generated by tools/promo_items.js from the game tables (game/src/55_promo.js prCatalog). Do not edit by hand.",\n "max_coins": 500,\n'
    + ' "items": [\n' + cat.items.map((x) => '  ' + JSON.stringify(x)).join(',\n') + '\n ],\n "treats": [\n' + cat.treats.map((x) => '  ' + JSON.stringify(x)).join(',\n') + '\n ]\n}\n';
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== out) { console.error('tools/promo_items.json is stale: run node tools/promo_items.js'); process.exit(1); }
    console.log('tools/promo_items.json is up to date (' + cat.items.length + ' items, ' + cat.treats.length + ' treats)'); return;
  }
  fs.writeFileSync(OUT, out);
  console.log('wrote tools/promo_items.json: ' + cat.items.length + ' items (' + cat.items.filter((x) => x.promo).length + ' code-only), ' + cat.treats.length + ' treats');
})().catch((e) => { console.error(e && e.stack || e); process.exit(1); });
