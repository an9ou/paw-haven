#!/usr/bin/env node
// v2.32 "A letter from your dog" (V232_letters.md 3): packs the letter's words for the Worker.
//   node tools/letters_pack.js            writes cloudflare/letters_text.js
//   node tools/letters_pack.js --check    exits 1 when that file is stale (the suite letters_worker runs it)
// From game/i18n/<lang>.json (12 languages): every lt.m_* message (the email, the confirmation email, the two small pages; their English
// lives in game/src/59b_letters.js ltM()), the breed names (data.breed_names.*) and the trick names (data.tricks.*.n). A key a language
// lacks is left out: the Worker falls back to English for it. The formatter is game/i18n/msg.js itself (plurals, Korean particles), wrapped
// so it runs as an ES module in the Worker and in node. Run it after the i18n tables change (the paw-i18n skill, step 3).
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..'), OUT = path.join(ROOT, 'cloudflare', 'letters_text.js');
const MSG = require(path.join(ROOT, 'game/i18n/msg.js'));
const LANGS = MSG.CODES.slice();
const text = {}, breeds = {}, tricks = {};
for (const l of LANGS) {
  const t = JSON.parse(fs.readFileSync(path.join(ROOT, 'game/i18n', l + '.json'), 'utf8'));
  text[l] = {}; breeds[l] = {}; tricks[l] = {};
  for (const k of Object.keys(t).sort()) {
    const v = t[k]; if (typeof v !== 'string' || !v) continue;
    let m;
    if (k.startsWith('lt.m_')) text[l][k.slice(3)] = v;
    else if ((m = k.match(/^data\.breed_names\.([a-z0-9_]+)$/))) breeds[l][m[1]] = v;
    else if ((m = k.match(/^data\.tricks\.([a-z0-9_]+)\.n$/))) tricks[l][m[1]] = v;
  }
}
if (!Object.keys(text.en).length) { console.error('letters_pack: no lt.m_* keys in game/i18n/en.json (run node tools/i18n_extract.js --en first)'); process.exit(2); }
for (const k of Object.keys(text.en)) { try { MSG.parse(text.en[k]); } catch (e) { console.error('letters_pack: en ' + k + ': ' + e.message); process.exit(2); } }
const J = (o) => JSON.stringify(o);
const msgSrc = fs.readFileSync(path.join(ROOT, 'game/i18n/msg.js'), 'utf8');
const out = `// GENERATED by tools/letters_pack.js from game/i18n/*.json and game/i18n/msg.js. Do not edit: run \`node tools/letters_pack.js\`.
// v2.32 "A letter from your dog" (V232_letters.md 3): the letter's words in ${LANGS.length} languages, the breed and trick names, and the game's own
// message formatter. A second module of the Worker "pawhaven-api" (tools/cf_api_deploy.sh uploads it next to worker.js).
const PawI18nMsg = (() => {
  const module = { exports: {} };
${msgSrc.replace(/\s+$/, '')}
  return module.exports;
})();
export const LT_LANGS = ${J(LANGS)};
export const LT_TEXT = ${J(text)};
export const LT_BREEDS = ${J(breeds)};
export const LT_TRICKS = ${J(tricks)};
export function ltFormat(msg, vars, lang) { return PawI18nMsg.format(String(msg), vars || {}, lang); }
`;
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== out) { console.error('letters_pack: cloudflare/letters_text.js is stale: run node tools/letters_pack.js'); process.exit(1); }
  console.log('letters_pack: cloudflare/letters_text.js is up to date'); process.exit(0);
}
fs.writeFileSync(OUT, out);
console.log('wrote cloudflare/letters_text.js: ' + LANGS.length + ' languages, ' + Object.keys(text.en).length + ' messages, ' + (out.length / 1024).toFixed(0) + ' KB (' + LANGS.map((l) => l + ' ' + Object.keys(text[l]).length).join(', ') + ')');
