// Doodle Doggo v2.14 PERF lane (PERF.md): the pieces of the split builds, shared by game/build.js (publish -> _split/, used by tools/pages.js,
// tools/itch.js and the doodledoggo.app /play/ copy) and tools/artifact.js.
//   - the pawi18n slot holds only game/i18n/msg.js, a small PAW_I18N (no texts: fonts and the file names) and game/i18n/loader.js;
//   - each other language is its own file lang/<code>.<hash>.js (that language's array, as in game/i18n/packed.js) plus the shared
//     lang/keys.<hash>.js, both loaded before the game script runs (the game is wrapped in PAW_I18N.run);
//   - the photo-mode fonts (game/src/35b_photo_fonts.js, about 143 KB) become photo_fonts.<hash>.js, loaded on the first photo (35_photo.js);
//   - the Google Fonts stylesheet no longer blocks the first paint (fontsLink).
//   - v2.15 (PERF.md 5): art worlds F (world/pawart_world_f.js, the v2.15 map) and G (world/pawart_world_g.js, the new places) become lazy chunks
//     world_<f|g>.<hash>.js, when their files exist: the core sets window.PAW_CHUNKS = { f: name, g: name } and the game's artChunk(name) adds the
//     <script> tag on first use (world F is preloaded when idle after the title). game/build.js leaves LAZY out of the split build's art slot.
// File names carry a hash of their text, so a host can cache them for good (tools/cf_site.js). The test harness (game/build.js, harness.js) keeps
// everything inline and never uses this.
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const sha8 = (s) => crypto.createHash('sha1').update(s).digest('hex').slice(0, 8);
const noClose = (s) => s.replace(/<\//g, '<\\/');
const CHUNKS = { f: 'world/pawart_world_f.js', g: 'world/pawart_world_g.js' }; // v2.15: the lazy art worlds (PERF.md 5)
// the shell's Google Fonts stylesheet, made non-blocking for the split builds: preloaded, switched to a stylesheet on load (display=swap stays in
// the URL), with a <noscript> copy. The game build (the test harness) and paw_haven_prototype.html keep the plain blocking link.
const FONTS_RE = /<link rel="stylesheet" href="(https:\/\/fonts\.googleapis\.com\/css2\?[^"]+)">/;
function fontsLink(html) {
  if (!FONTS_RE.test(html)) throw new Error('split: the Google Fonts <link> is missing from game/shell.html');
  return html.replace(FONTS_RE, (m, u) => `<link rel="preload" as="style" href="${u}" onload="this.onload=null;this.rel='stylesheet'"><noscript><link rel="stylesheet" href="${u}"></noscript>`);
}
function make(root, opt) { // opt.lazy false: no lazy art chunks (tools/artifact.js keeps every world inline)
  const rd = (f) => fs.readFileSync(path.join(root, f), 'utf8');
  const w = {}; new Function('window', rd('game/i18n/packed.js'))(w); const P = w.PAW_I18N;
  if (!P || !Array.isArray(P.keys)) throw new Error('split: game/i18n/packed.js has no keys');
  // the keys (the same for every language, about 36 KB gzipped) are one shared file, lang/keys.<hash>.js, loaded next to the language's file
  const files = {}, names = {};
  const keysText = `/* Doodle Doggo: the text keys. Generated by tools/split.js from game/i18n/packed.js. */\n(function(P){if(P)P.keys=${noClose(JSON.stringify(P.keys))};})(window.PAW_I18N);\n`;
  const keysName = `lang/keys.${sha8(keysText)}.js`; files[keysName] = keysText;
  for (const code of Object.keys(P).filter((k) => k !== 'keys' && Array.isArray(P[k]))) {
    const text = `/* Doodle Doggo: the ${code} texts, one per key of ${keysName}. Generated by tools/split.js from game/i18n/packed.js. */\n`
      + `(function(P){if(P)P[${JSON.stringify(code)}]=${noClose(JSON.stringify(P[code]))};})(window.PAW_I18N);\n`;
    const name = `lang/${code}.${sha8(text)}.js`; files[name] = text; names[code] = name;
  }
  // the photo fonts: the same CSS text, as its own file; the game gets a stub (35_photo.js loads the file on first use)
  const pf = rd('game/src/35b_photo_fonts.js'), m = /const PH_FONT_CSS = ("(?:[^"\\]|\\.)*");/.exec(pf);
  if (!m) throw new Error('split: game/src/35b_photo_fonts.js has no PH_FONT_CSS');
  const pfText = `/* Doodle Doggo: the photo postcard fonts. Generated by tools/split.js from game/src/35b_photo_fonts.js. */\nwindow.PAW_PH_FONTS = ${m[1]};\n`;
  const pfName = `photo_fonts.${sha8(pfText)}.js`; files[pfName] = pfText;
  // v2.15: the lazy art worlds (only those whose file exists; the one-file builds, the artifact and the harness keep them inline)
  const chunks = {};
  for (const [k, f] of Object.entries(CHUNKS)) {
    if ((opt && opt.lazy === false) || !fs.existsSync(path.join(root, f))) continue;
    const src = rd(f); if (/<\/script/i.test(src)) throw new Error('split: </script in ' + f);
    const text = `/* Doodle Doggo: art world ${k.toUpperCase()}, loaded on first use (artChunk). Generated by tools/split.js from ${f}. */\n${src}\n`;
    const name = `world_${k}.${sha8(text)}.js`; files[name] = text; chunks[k] = name;
  }
  const stub = `/* v2.14 PERF (tools/split.js): the photo fonts load on first use from ${pfName} (35_photo.js phFonts) */\nlet PH_FONT_CSS = '';\nconst PH_FONT_FILE = ${JSON.stringify(pfName)};\nconst phFontsSet = (css) => { PH_FONT_CSS = css; };\n`;
  // the game script: the photo stub in place of 35b_photo_fonts.js, then the whole script waits for its language (loader.js PAW_I18N.run)
  const game = (js) => {
    if (js.split(pf).length !== 2) throw new Error('split: 35b_photo_fonts.js not found once in the game script');
    return '(window.PAW_I18N && window.PAW_I18N.run || function (f) { f(); })(function () {\n' + js.replace(pf, () => stub) + '\n});\n';
  };
  const core = rd('game/i18n/msg.js') + '\n' + `window.PAW_I18N = ${noClose(JSON.stringify({ v: P.v, keys: [], fonts: P.fonts || {}, keyFile: keysName, files: names }))};\n` + rd('game/i18n/loader.js')
    + (Object.keys(chunks).length ? `\nwindow.PAW_CHUNKS = ${JSON.stringify(chunks)};\n` : '');
  return { core, files, game, names, fontsLink, chunks, lazy: Object.keys(chunks).map((k) => CHUNKS[k]) };
}
module.exports = { make, sha8, fontsLink, CHUNKS };
