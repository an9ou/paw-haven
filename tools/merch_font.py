#!/usr/bin/env python3
"""Merch spike: the game's handwriting font (Caveat, the name on the share picture and the photo chip) as glyph outlines for PawPrint.

    python3 tools/merch_font.py            (needs fontTools + brotli; the output is committed, so nobody else needs Python)

Writes merch/pawprint_font.js: window-free `PAWPRINT_FONT = { upm, asc, desc, cap, g: { "<char>": [advance, "path d"] } }`.
Caveat is a variable font (wght 400-700): the outlines are the Bold (700) instance, the weight the share picture uses for the dog's name.
Sources: site/fonts/caveat.woff2 (Latin, Latin-1, OE/oe) + tools/fonts/caveat-macron.woff2 (O/o/U/u with macron, for romaji names).
Outlines instead of a font file: every renderer (a browser canvas, resvg in a Worker, Chromium) draws the same letters, nothing to load or embed,
and a print file never falls back to another font. No kerning or contextual alternates (a handwriting face; the difference is small).
"""
import io, json, os, sys
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SRC = [os.path.join(ROOT, 'site', 'fonts', 'caveat.woff2'), os.path.join(ROOT, 'tools', 'fonts', 'caveat-macron.woff2')]
OUT = os.path.join(ROOT, 'merch', 'pawprint_font.js')


def r(v):
    v = round(v)
    return str(int(v))


def bold(path):
    f = TTFont(path)
    return instancer.instantiateVariableFont(f, {'wght': 700})


glyphs, meta = {}, None
for src in SRC:
    f = bold(src)
    gs, cmap, hmtx = f.getGlyphSet(), f.getBestCmap(), f['hmtx']
    if meta is None:
        os2 = f['OS/2']
        meta = {'upm': f['head'].unitsPerEm, 'asc': os2.sTypoAscender, 'desc': os2.sTypoDescender, 'cap': getattr(os2, 'sCapHeight', 700) or 700}
    for cp, gname in sorted(cmap.items()):
        ch = chr(cp)
        if ch in glyphs or cp < 0x20 or (0x7F <= cp < 0xA0) or cp == 0xAD:
            continue
        pen = SVGPathPen(gs, ntos=r)
        gs[gname].draw(TransformPen(pen, (1, 0, 0, -1, 0, 0)))  # y down, baseline at 0
        glyphs[ch] = [hmtx[gname][0], pen.getCommands()]

meta['g'] = glyphs
js = ('/* generated by tools/merch_font.py: Caveat Bold (SIL OFL 1.1) as outlines, y down, baseline 0, units per em ' + str(meta['upm']) + '. Do not edit. */\n'
      'var PAWPRINT_FONT = ' + json.dumps(meta, ensure_ascii=False, separators=(',', ':')) + ';\n'
      "if (typeof module !== 'undefined' && module.exports) module.exports = PAWPRINT_FONT;\n")
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w', encoding='utf-8') as fh:
    fh.write(js)
print('merch/pawprint_font.js:', len(glyphs), 'glyphs,', len(js.encode('utf-8')), 'bytes')
