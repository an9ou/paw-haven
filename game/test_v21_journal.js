  await closeAll();

  sec('Profile: ancestry line and Proud Mum');
  await t.patch({ dog: { anc: null } }); // v2.1 merge: BREED backfills anc on load, and patch() merges objects
  await t.patch({ dog: { anc: { corgi: 0.75, husky: 0.25 }, proud: '2026-02-02' } });
  await openJ('profile'); await p.waitForSelector('.profile');
  ok(/Corgi, 1\/4 Husky/.test(await p.textContent('.ancline')), 'ancestry line: Corgi, 1/4 Husky');
  ok(await p.locator('.titlebadge.proud').count() === 1, 'Proud Mum badge'); await t.SH('profile');
  await closeAll();

  sec('Family tab: Find a partner');
  await t.patch({ dog: { born: await ago(400), fixed: false } });
  await openJ('family'); await p.waitForSelector('.famwrap');
  ok(await p.locator('.fpartner').count() === 1, 'Find a partner on a grown-up dog at home');
  await p.click('.fpartner'); await t.until(() => !document.querySelector('.panel.journal'), null, 4000);
  ok(await ev(() => !document.querySelector('.panel.journal') && !document.getElementById('modal').hidden), 'it closes the Journal and opens the Playdates popup');
  await closeAll();
  await t.patch({ dog: { fixed: true } }); await openJ('family'); await p.waitForSelector('.famwrap');
  ok(await p.locator('.fpartner').count() === 0, 'hidden for a fixed dog'); await closeAll();
  await t.patch({ dog: { fixed: false, born: await ago(1) } }); await openJ('family'); await p.waitForSelector('.famwrap');
  ok(await p.locator('.fpartner').count() === 0, 'hidden for a puppy'); await closeAll();
  await t.patch({ dog: { born: await ago(400) } });

  sec('family rewards: gen3 and gen5');
  await ev(() => { const S = window.__paw.S; S.famRewards = {}; delete S.portrait; delete S.decor; });
  const T3 = { g1: { id: 'g1', name: 'Gran', key: 'corgi', sex: 'female', status: 'npc', parents: null }, m1: { id: 'm1', name: 'Mum', key: 'corgi', sex: 'female', status: 'npc', parents: { dam: 'g1', sire: null } } };
  await t.patch({ tree: T3, dog: { parents: { dam: 'm1', sire: null } } });
  await openJ('family'); await p.waitForSelector('.famwrap'); s = await S();
  ok(!!s.famRewards.gen3 && s.decor && s.decor['Family Photo Frame'] && s.decor['Family Photo Frame'].out === true, '3 generations: Family Photo Frame');
  ok(s.portrait && s.portrait.ids.includes(me) && s.portrait.ids.length <= 4, 'portrait set to that line when there was none');
  ok(!s.famRewards.gen5 && !s.titles['Great-Great-Granddog'], 'no gen5 title yet');
  await closeAll();
  await ev(() => { const S = window.__paw.S; S.portrait = { date: '2020-01-01', ids: ['keep'] }; delete S.famRewards.gen3; delete S.decor; });
  await ev(() => window.__paw.jrFamCheck()); s = await S();
  ok(s.famRewards.gen3 && s.portrait.ids.join() === 'keep', 'an existing portrait is kept');
  const T5 = { g2: { id: 'g2', name: 'GreatGran', key: 'corgi', sex: 'female', status: 'npc', parents: null }, g1: { id: 'g1', name: 'Gran', key: 'corgi', sex: 'female', status: 'npc', parents: { dam: 'g2', sire: null } }, g0: { id: 'g0', name: 'Old Gran', key: 'corgi', sex: 'female', status: 'npc', parents: { dam: 'g1', sire: null } } };
  await ev((o) => { const S = window.__paw.S; Object.assign(S.tree, o.T); S.tree.g1.parents = { dam: 'g2', sire: null }; S.tree.m1.parents = { dam: 'g0', sire: null }; }, { T: T5 });
  await ev(() => window.__paw.jrFamCheck()); s = await S();
  ok(!!s.famRewards.gen5 && !!s.titles['Great-Great-Granddog'], '5 generations: Great-Great-Granddog'); const gen5 = s.famRewards.gen5;
  await ev(() => window.__paw.jrFamCheck()); s = await S(); ok(s.famRewards.gen5 === gen5, 'gen5 given once');

  sec('Glitter Legend');
  await ev(() => { const S = window.__paw.S; S.sparkleBook = {}; window.PawGenes.BREEDS.slice(0, 9).forEach((k) => { S.sparkleBook[k] = '2026-03-03'; }); });
  await ev(() => window.__paw.jrFamCheck()); s = await S(); ok(!s.titles['Glitter Legend'], '9 of 10 Sparkle breeds: not yet');
  await ev(() => { const S = window.__paw.S; S.sparkleBook[window.PawGenes.BREEDS[9]] = '2026-03-03'; window.__paw.jrFamCheck(); }); s = await S();
  ok(!!s.famRewards.glitter && !!s.titles['Glitter Legend'], 'Sparkle pup of all 10 breeds: Glitter Legend');

