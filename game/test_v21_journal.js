  ok(/the Tanakas/.test(await p.textContent('.al-slot.found')) && /1 \/ 12/.test(await p.textContent('.al-head')), 'found slot shows the family name');
  await t.SH('mailbox_album');
  await p.click('[data-mbt=letters]'); await p.waitForSelector('.mbox'); await closeAll();
