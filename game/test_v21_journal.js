  ok(s.coins === c0 + 40 + 80 && (await mail('pp_pp1_d30')).length === 1, 'day 30: +80 coins, once');
  ok((await mail('pp_pp1_d14')).length === 1 && s.mailCards.pp1.paid.d14 && s.mailCards.pp1.paid.d30, 'paid marks kept on the schedule record');
  await ev(() => window.__paw.mailTick()); s = await S(); ok(s.coins === c0 + 120, 'still no double pay');
