  await setBook(49); await openJ('coats'); await p.waitForSelector('.ctop'); s = await S();
  ok(!!s.coatRewards[50] && !!s.titles['Master Breeder'], '50 coats: Master Breeder is in S.titles too');
  ok(await p.locator('.cmile').count() === 7 && /Rainbow Collar/.test(await p.textContent('.cmiles')), 'reward track shows 7 steps');
  await closeAll();

  sec('Sparkle Meter jar');
  await t.patch({ pupsSinceSparkle: 7 });
  await openJ('coats'); await p.waitForSelector('.cjar');
  ok(await p.getAttribute('.cjar', 'data-fill') === '7' && /7 \/ 24/.test(await p.textContent('.cjar')), 'jar fill 7 / 24');
  ok(/guaranteed by puppy 24/.test(await p.textContent('.cjar')), 'jar caption');
  ok(await p.locator('.cjar-art svg').count() >= 1, 'jar art drawn'); await t.SH('coats');
  await closeAll();
