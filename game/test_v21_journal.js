  ok(await p.getAttribute('.cjar', 'data-fill') === '24', 'jar full at 24'); await closeAll();
  await t.patch({ pupsSinceSparkle: 0 });

  sec('Breeds & Mixes strip');
  const key = s0.dog.key;
  await t.patch({ tree: { sled1: { id: 'sled1', name: 'Noodle Roll', key: 'corgi', sex: 'male', status: 'npc', mix: { a: 'corgi', b: 'husky', name: 'Sled Noodle', grand: 'Sled Noodle' }, anc: { corgi: 0.375, husky: 0.375, dachs: 0.25 }, parents: null } } });
