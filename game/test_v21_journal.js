  await closeAll(); await t.home('yard');
  await setBook(39); await openJ('coats'); await p.waitForSelector('.ctop'); s = await S();
  ok(!!s.coatRewards[40] && s.decor && s.decor['Giant Crayon Box'] && s.decor['Giant Crayon Box'].out === true, '40 coats: Giant Crayon Box yard decoration');
