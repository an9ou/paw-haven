  const pup = (o) => Object.assign({ id: 'pp1', name: 'Bean', key: 'corgi', sex: 'female', genes: { B: ['B', 'B'], D: ['D', 'D'], E: ['E', 'E'], S: ['S', 'S'], M: ['m', 'm'], Bl: ['bl', 'bl'] }, parents: null, family: fam, mix: null, sparkle: false }, o);
  const mail = async (id) => (await S()).mail.filter((m) => m.id === id);
  await ev(() => { const S = window.__paw.S; S.mail = []; S.penpals = {}; S.mailCards = {}; });
