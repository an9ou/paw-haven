  ok(await p.locator('.cmixes .mchip.breed.found').count() >= 3, 'found breeds listed (own breed, corgi, husky, dachs)');
  ok(await p.locator('.cmixes .mchip.breed').count() >= 10, 'all breeds have a chip');
  await closeAll();

  sec('titles: toggle on the name tag, old Treasure Legend migrated');
  await ev(() => { const S = window.__paw.S; S.titles = {}; S.coatRewards = {}; S.coatBook = {}; S.title = 'Treasure Legend'; });
  await openJ('profile'); await p.waitForSelector('.pf-titles');
  s = await S(); ok(!!s.titles['Treasure Legend'], 'Treasure Legend moved into S.titles');
  await ev(() => window.__paw.titleGive('Gene Detective')); s = await S();
  ok(s.title === 'Treasure Legend' && !!s.titles['Gene Detective'], 'titleGive adds once and keeps the title that is shown');
  await ev(() => window.__paw.titleGive('Gene Detective')); s = await S(); ok(Object.keys(s.titles).length === 2, 'titleGive twice: still one entry');
  await closeAll(); await openJ('profile'); await p.waitForSelector('.pf-titles .ptitle');
  ok(await p.locator('.ptitle').count() === 2, 'Profile lists 2 titles');
  await p.click('[data-jtitle="Gene Detective"]'); await p.waitForSelector('.ptitle.on[data-jtitle="Gene Detective"]');
